"""Write the Documentation tab: one mkdocstrings page per module of ``nnterp``, and its nav.

Run from anywhere::

    python site/gen_reference.py

It walks the ``nnterp`` package next to this folder, writes ``site/docs/documentation/`` (one
``.md`` per module, an ``index.md`` per package listing its submodules) and replaces the nav
between the two ``reference nav`` markers in ``site/mkdocs.yml``. Pages it did not write are
removed, so the tab always mirrors the source tree. Private modules, ``_version`` and the
in-package ``tests`` are skipped.
"""

from __future__ import annotations

from pathlib import Path
import shutil

HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parent / "nnterp"
OUT = HERE / "docs" / "documentation"
CONFIG = HERE / "mkdocs.yml"
START = "  # --- reference nav: generated by gen_reference.py, do not edit by hand ---\n"
END = "  # --- end reference nav ---\n"
SKIP = {"tests", "data", "__pycache__"}

INDEX_INTRO = """# API Reference

Auto-generated reference for the `nnterp` package, organized to mirror the source tree.
Most users need `StandardizedTransformer` and the values on the components; the rest documents
the internals.

"""


def modules(package: Path):
    """Yield (dotted name, is_package) for the package and every module under it, in source order."""
    yield ".".join(package.relative_to(PACKAGE.parent).parts), True
    for child in sorted(package.iterdir()):
        if child.name in SKIP or child.name.startswith("_"):
            continue
        if child.is_dir() and (child / "__init__.py").exists():
            yield from modules(child)
        elif child.suffix == ".py":
            yield ".".join(child.relative_to(PACKAGE.parent).with_suffix("").parts), False


def page_path(name: str, is_package: bool) -> Path:
    parts = name.split(".")[1:]  # drop the leading "nnterp"
    return Path(*parts, "index.md") if is_package else Path(*parts).with_suffix(".md")


def main() -> None:
    entries = list(modules(PACKAGE))
    children: dict[str, list[tuple[str, bool]]] = {}
    for name, is_package in entries:
        parent = name.rpartition(".")[0]
        if parent:
            children.setdefault(parent, []).append((name, is_package))

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for name, is_package in entries:
        path = OUT / page_path(name, is_package)
        path.parent.mkdir(parents=True, exist_ok=True)
        title = name.rpartition(".")[2]
        body = (INDEX_INTRO if name == "nnterp" else f"# {title}\n\n") + f"::: {name}\n"
        if is_package and children.get(name):
            body += "\n## Submodules\n\n"
            for child, child_is_package in children[name]:
                short = child.rpartition(".")[2]
                link = f"{short}/index.md" if child_is_package else f"{short}.md"
                body += f"- [{short}]({link})\n"
        path.write_text(body)

    def nav(name: str, is_package: bool, depth: int) -> str:
        indent = "  " * depth
        short = name.rpartition(".")[2]
        rel = f"documentation/{page_path(name, is_package).as_posix()}"
        if not is_package:
            return f"{indent}- {short}: {rel}\n"
        out = f"{indent}- {short}:\n{indent}  - {rel}\n"
        for child, child_is_package in children.get(name, []):
            out += nav(child, child_is_package, depth + 1)
        return out

    block = "  - Documentation:\n    - documentation/index.md\n    - API at a glance: reference/api-at-a-glance.md\n    - Glossary: reference/glossary.md\n"
    for child, child_is_package in children["nnterp"]:
        block += nav(child, child_is_package, 2)

    text = CONFIG.read_text()
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    CONFIG.write_text(head + START + block + END + tail)
    print(f"{len(entries)} pages written under {OUT.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
